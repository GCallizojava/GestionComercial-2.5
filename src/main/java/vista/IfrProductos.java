    private void tblProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductosMouseClicked
       int fila = tblProductos.getSelectedRow();

if (fila >= 0) {
    int filaModelo = tblProductos.convertRowIndexToModel(fila);

    txtId.setText(tblProductos.getModel().getValueAt(filaModelo, 0).toString());
    txtCodigo.setText(tblProductos.getModel().getValueAt(filaModelo, 1).toString());
    txtNombre.setText(tblProductos.getModel().getValueAt(filaModelo, 2).toString());
    txtDescripcion.setText(tblProductos.getModel().getValueAt(filaModelo, 3).toString());
    txtPrecio.setText(tblProductos.getModel().getValueAt(filaModelo, 4).toString());
    txtExistencia.setText(tblProductos.getModel().getValueAt(filaModelo, 5).toString());
    try {
    String codigo = txtCodigo.getText().trim();

    dao.ProductoDAOImpl dao = new dao.ProductoDAOImpl();
    modelo.Producto producto = dao.buscarPorCodigo(codigo);

    

        if (producto != null) {
    imagenProducto = producto.getImagen();

    util.ImagenUtil.mostrarImagen(
        imagenProducto, lblImagen, 150, 150
    );
}
    
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al cargar imagen: " + e.getMessage()
    );
}
}
    }//GEN-LAST:event_tblProductosMouseClicked


